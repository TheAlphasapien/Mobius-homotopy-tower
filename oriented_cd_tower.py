if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--min-level', type=int, default=4)
    p.add_argument('--max-level', type=int, default=8,
                   help='k=14 ≈ 7h, k=15 > 2 days')
    p.add_argument('--single',    type=int, default=None,
                   help='Analyse a single level and exit')
    p.add_argument('--compat-rate', action='store_true',
                   help='Run 25%% compatibility rate test instead of full report')
    args = p.parse_args()

    if args.single is not None:
        report(min_level=args.single, max_level=args.single)
    elif args.compat_rate:
        compat_rate_report(min_level=args.min_level, max_level=args.max_level)
    else:
        report(min_level=args.min_level, max_level=args.max_level)
